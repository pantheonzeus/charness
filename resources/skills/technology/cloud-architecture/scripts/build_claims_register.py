#!/usr/bin/env python3
"""Build the claims register for this skill's references, in the table format
_shared/scripts/evidence_lint.py reads (Claim | Tag | Source).

Every line in references/*.md carrying a provenance tag becomes one row:
  [F] / [F, ...]  -> observed            (source = footnote URLs on the line)
  [F*]            -> observed (unfetched) (canonical source cited from prior knowledge)
  [I] / [I, ...]  -> inferred            (source = footnote URLs, else the section it derives from)
  [U]             -> assumed (flagged)   (disclosed as unconfirmed in the reference itself)
A line mixing [F] and [I] is registered as "observed; inferred".
An [F] line with no footnote gets an empty source, so the lint reports it as UNCITED.

Usage: python3 scripts/build_claims_register.py   (from the skill folder or anywhere)
Writes references/EVIDENCE.md, then run:
  python3 ../../_shared/scripts/evidence_lint.py references/EVIDENCE.md
"""
import re
from pathlib import Path

SKILL = Path(__file__).resolve().parent.parent
REFS = SKILL / "references"
SKIP = {"EVIDENCE.md", "templates.md"}

TAG = re.compile(r"\[(F\*|F|I|U)(?:[,/][^\]]*)?\]")
FOOT_USE = re.compile(r"\[\^([\w-]+)\](?!:)")
FOOT_DEF = re.compile(r"^\[\^([\w-]+)\]:\s*(.+)$", re.M)
URL = re.compile(r"https?://\S+")


def clean(text, limit=170):
    text = FOOT_USE.sub("", TAG.sub("", text))
    text = re.sub(r"[*`]|^\s*[-|>\d.]+\s*", "", text).replace("|", "/").strip(" :—-")
    text = re.sub(r"\s+", " ", text)
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "…"


def main():
    rows = []
    for ref in sorted(REFS.glob("*.md")):
        if ref.name in SKIP:
            continue
        body = ref.read_text(encoding="utf-8")
        foot = {k: " · ".join(URL.findall(v)) or v for k, v in FOOT_DEF.findall(body)}
        section = ""
        lines = body.splitlines()
        for n, line in enumerate(lines, 1):
            if line.startswith("#"):
                section = line.lstrip("# ").strip()
                continue
            if FOOT_DEF.match(line) or line.lstrip().startswith("*Snapshot"):
                continue
            kinds = {m.group(1) for m in TAG.finditer(line)}
            if not kinds:
                continue
            keys = FOOT_USE.findall(line)
            if not keys and line.rstrip().endswith(":"):
                # header claim ("**For** [F]:") — its sources sit on the lines below, up to the next blank/heading
                for nxt in lines[n:]:
                    if not nxt.strip() or nxt.startswith("#"):
                        break
                    keys += FOOT_USE.findall(nxt)
            srcs = " · ".join(dict.fromkeys(foot.get(k, f"MISSING ^{k}") for k in keys))
            if "U" in kinds:
                tag, src = "assumed (flagged)", srcs or f"flagged [U] in {ref.name}"
            elif kinds & {"F", "F*"}:
                tag = "observed" + (" (unfetched)" if kinds == {"F*"} else "")
                tag += "; inferred" if "I" in kinds else ""
                src = srcs
            else:
                tag, src = "inferred", srcs or f"derived from cited sources in {ref.name} § {section}"
            rows.append((clean(line), tag, src or "", f"{ref.name}:{n}"))

    out = [
        "# Claims register — cloud-architecture references",
        "",
        "*Generated by `scripts/build_claims_register.py` — do not hand-edit; re-run after changing a reference. "
        "Lint: `python3 resources/skills/_shared/scripts/evidence_lint.py resources/skills/technology/cloud-architecture/references/EVIDENCE.md`.*",
        "",
        "| # | Claim | Tag | Source | Where |",
        "|---|---|---|---|---|",
    ]
    out += [f"| {i} | {c} | {t} | {s} | {w} |" for i, (c, t, s, w) in enumerate(rows, 1)]
    (REFS / "EVIDENCE.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"rows={len(rows)} -> {REFS / 'EVIDENCE.md'}")


if __name__ == "__main__":
    main()
